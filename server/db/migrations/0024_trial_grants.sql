-- 0024 (2026-11-25, вне бесед): пробный подарок — не больше одного на АДРЕС.
-- uq_transactions_trial (0023) держит «один на учётную запись», но удаление
-- учётной записи освобождает адрес, и новая регистрация на тот же ящик
-- получала подарок снова. Здесь — отпечаток адреса (SHA-256 нормализованного
-- адреса, billing-service trialEmailHash), без ссылки на пользователя.
-- Подарки, выданные до этой миграции, записываются при следующем
-- подтверждении адреса или при удалении учётной записи (account-deletion).
CREATE TABLE "trial_grants" (
	"email_hash" text PRIMARY KEY NOT NULL,
	"created_at" timestamp with time zone DEFAULT now() NOT NULL
);
