def patch(path: str, old: str, new: str, tag: str, marker: str | None = None) -> None:
    """Точечная замена; probe (по умолчанию — новый текст) даёт идемпотентность.

    Если новый текст неуникален в файле, probe срабатывает ложно и правка
    молча уходит в skip — тогда якорь берётся многострочным блоком либо
    marker задаётся явно (грабля первого предпатча).
    """
    p = Path(path)
    if not p.exists():
        failed.append(f"{tag}: файл не найден — {path}"); return
    s = p.read_text(encoding="utf-8")
    probe = marker if marker is not None else new
    if probe in s:
        skipped.append(tag); return
    if old not in s:
        failed.append(f"{tag}: якорь не найден в {path}"); return
    p.write_text(s.replace(old, new, 1), encoding="utf-8")
    applied.append(tag)


def check_order() -> bool:
    p = Path(PROTOCOL)
    if not p.exists():
        failed.append(f"порядок: не найден {PROTOCOL}"); return False
    s = p.read_text(encoding="utf-8")
    miss = []
    if GUARD1 not in s: miss.append("patch-docs-conv16-pre.py (нет беседы 1.6b)")
    if GUARD2 not in s: miss.append("patch-docs-conv23-pre.py (нет рекомендации 2.4 перед 2.3)")
    if miss:
        failed.append("порядок: сперва нужно применить " + " и ".join(miss))
        return False
    return True


if not check_order():
    print("APPLIED: 0"); print("SKIPPED: 0"); print("FAILED:", len(failed))
    for _t in failed: print("  !", _t)
    raise SystemExit(1)


