ROOT = Path(__file__).resolve().parent.parent.parent
applied = skipped = failed = 0


def patch(rel, old, new, label, marker=None):
    global applied, skipped, failed
    path = ROOT / rel
    text = path.read_text(encoding="utf-8")
    if new in text or (marker and marker in text):
        skipped += 1; print(f"  skip  {label}"); return
    if text.count(old) != 1:
        failed += 1; print(f"  fail  {label}: якорь встречается {text.count(old)} раз"); return
    path.write_text(text.replace(old, new), encoding="utf-8")
    applied += 1; print(f"  ok    {label}")


