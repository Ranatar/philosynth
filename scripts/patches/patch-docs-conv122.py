import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
applied = skipped = failed = 0


def _load(rel: str, label: str):
    global failed
    path = ROOT / rel
    if not path.exists():
        failed += 1
        print(f"  fail  {label}: нет файла {rel}")
        return None, None
    return path, path.read_text(encoding="utf-8")


def patch(rel: str, old: str, new: str, label: str, marker: str | None = None) -> None:
    global applied, skipped, failed
    path, text = _load(rel, label)
    if path is None:
        return
    if new in text or (marker and marker in text):
        skipped += 1
        print(f"  skip  {label}")
        return
    if text.count(old) != 1:
        failed += 1
        print(f"  fail  {label}: якорь встречается {text.count(old)} раз")
        return
    path.write_text(text.replace(old, new), encoding="utf-8")
    applied += 1
    print(f"  ok    {label}")


def insert_after_line(rel: str, prefix: str, block: str, label: str, marker: str) -> None:
    """Вставить block отдельными строками сразу после ЕДИНСТВЕННОЙ строки с prefix."""
    global applied, skipped, failed
    path, text = _load(rel, label)
    if path is None:
        return
    if marker in text:
        skipped += 1
        print(f"  skip  {label}")
        return
    lines = text.split("\n")
    hits = [i for i, l in enumerate(lines) if l.startswith(prefix)]
    if len(hits) != 1:
        failed += 1
        print(f"  fail  {label}: строка-якорь встречается {len(hits)} раз")
        return
    lines[hits[0] + 1 : hits[0] + 1] = block.split("\n")
    path.write_text("\n".join(lines), encoding="utf-8")
    applied += 1
    print(f"  ok    {label}")


