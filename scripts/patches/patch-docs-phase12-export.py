applied = skipped = failed = 0


def rd(rel):
    return (ROOT / rel).read_text(encoding="utf-8")


def wr(rel, text):
    (ROOT / rel).write_text(text, encoding="utf-8")


def res(kind, label, why=""):
    global applied, skipped, failed
    if kind == "ok":
        applied += 1
    elif kind == "skip":
        skipped += 1
    else:
        failed += 1
    print(f"  {kind:5} {label}" + (f": {why}" if why else ""))


def patch(rel, old, new, label, done_marker=None):
    text = rd(rel)
    if new in text or (done_marker is not None and done_marker in text):
        return res("skip", label)
    if text.count(old) != 1:
        return res("fail", label, f"исходный фрагмент встречается {text.count(old)} раз")
    wr(rel, text.replace(old, new))
    res("ok", label)


def insert_before(rel, anchor, addition, label, marker):
    text = rd(rel)
    if marker in text:
        return res("skip", label)
    if text.count(anchor) != 1:
        return res("fail", label, f"якорь встречается {text.count(anchor)} раз")
    wr(rel, text.replace(anchor, addition + anchor))
    res("ok", label)


def insert_after(rel, anchor, addition, label, marker):
    text = rd(rel)
    if marker in text:
        return res("skip", label)
    if text.count(anchor) != 1:
        return res("fail", label, f"якорь встречается {text.count(anchor)} раз")
    wr(rel, text.replace(anchor, anchor + addition))
    res("ok", label)




def replace_row(num, new_line, label):
    text = rd(P07)
    if new_line in text:
        return res("skip", label)
    m = re.search(r"^\| " + re.escape(num) + r" \|.*$", text, re.M)
    if not m:
        return res("fail", label, "строка не найдена")
    wr(P07, text.replace(m.group(0), new_line))
    res("ok", label)


