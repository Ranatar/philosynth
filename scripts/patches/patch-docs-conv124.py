import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
applied = skipped = failed = 0


def _load(rel: str, label: str):
    global failed
    path = ROOT / rel
    if not path.exists():
        failed += 1
        print(f"  fail  {label}: нет файла {rel}")
        return None, None
    return path, path.read_text(encoding="utf-8")


# Правки части I, чей текст закрытие беседы законно меняет (строки §12
# снимаются при закрытии): узнаются по маркеру блока завершения (09 §2, 12.3).
CLOSE_MARK_124 = "**По факту 12.4 (завершение — беседа закрыта"
SUPERSEDED = {
    "B1 07 §12: состояние строк 12.4",
    "B2 07 §12: строка Д-49",
}


def _superseded(label: str, text: str) -> bool:
    return label in SUPERSEDED and CLOSE_MARK_124 in text


def patch(rel: str, old: str, new: str, label: str, marker: str | None = None) -> None:
    global applied, skipped, failed
    path, text = _load(rel, label)
    if path is None:
        return
    if new in text or (marker and marker in text) or _superseded(label, text):
        skipped += 1
        print(f"  skip  {label}")
        return
    if text.count(old) != 1:
        failed += 1
        print(f"  fail  {label}: якорь встречается {text.count(old)} раз")
        return
    path.write_text(text.replace(old, new), encoding="utf-8")
    applied += 1
    print(f"  ok    {label}")


