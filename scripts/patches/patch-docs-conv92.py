def insert_before_next(rel: str, unique: str, marker: str, addition: str, label: str) -> None:
    """Вставка перед первым marker ПОСЛЕ уникального якоря (якорь не меняется)."""
    global applied, skipped, failed
    path = ROOT / rel
    text = path.read_text(encoding="utf-8")
