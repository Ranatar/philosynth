def replace_between(rel: str, start: str, end: str, new: str, label: str, marker: str) -> None:
    """Заменить текст от start (включая) до end (не включая)."""
    global applied, skipped, failed
    path, text = _load(rel, label)
    if path is None:
        return
    if marker in text:
        skipped += 1
        print(f"  skip  {label}")
        return
    if text.count(start) != 1 or text.count(end) != 1 or text.index(start) > text.index(end):
        failed += 1
        print(f"  fail  {label}: границы — start ×{text.count(start)}, end ×{text.count(end)}")
        return
    a, b = text.index(start), text.index(end)
    path.write_text(text[:a] + new + text[b:], encoding="utf-8")
    applied += 1
    print(f"  ok    {label}")


