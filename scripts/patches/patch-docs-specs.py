from pathlib import Path

applied, skipped, failed = [], [], []


def patch(path: str, old: str, new: str, tag: str) -> None:
    p = Path(path)
    if not p.exists():
        failed.append(f"{tag}: нет файла {path}")
        return
    text = p.read_text(encoding="utf-8")
    if new in text:
        skipped.append(tag)
        return
    if old not in text:
        failed.append(f"{tag}: якорь не найден в {path}")
        return
    if text.count(old) > 1:
        failed.append(f"{tag}: якорь неуникален в {path} ({text.count(old)})")
        return
    p.write_text(text.replace(old, new, 1), encoding="utf-8")
    applied.append(tag)


P07 = "docs/07-conversation-protocol.md"
README = "README.md"

