#!/usr/bin/env python3
"""Патч документации: единство стилей клиента с исходником (2026-09-02).

Что фиксируем в доках:
  * 04 — строка про «CSS документа» описывала ПОДМНОЖЕСТВО правил; теперь
    globals.css несёт ДОСЛОВНЫЙ порт всего блока <style> исходника.
  * 05 — комментарий к globals.css (три части файла) и порядок директив.
  * 07 — чек CSS беседы 0.4 дополнен требованием паритета; в конец
    протокола добавлена глава «Единство стилей с исходником» с правилом
    работы, инструментом проверки и списком отклонений сервиса.
  * README — строка о состоянии.

Скрипт идемпотентен: повторный прогон даёт skip по каждой правке.
Отчёт: applied / skip / fail.

Запуск из корня репозитория:  python3 scripts/patch-docs-css-parity.py
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

applied = 0
skipped = 0
failed = 0


def patch(rel_path: str, old: str, new: str, label: str) -> None:
    """Заменяет old на new. new-in-text проверяется ПЕРВЫМ: в дописываниях
    old — префикс new, иначе повторный прогон продублирует блок."""
    global applied, skipped, failed
    path = ROOT / rel_path
    if not path.exists():
        failed += 1
        print(f"  fail  {label}: нет файла {rel_path}")
        return
    text = path.read_text(encoding="utf-8")
    if new in text:
        skipped += 1
        print(f"  skip  {label}")
        return
    if old not in text:
        failed += 1
        print(f"  fail  {label}: не найден исходный фрагмент")
        return
    path.write_text(text.replace(old, new, 1), encoding="utf-8")
    applied += 1
    print(f"  ok    {label}")


