/**
 * Веса признаков (сумма 100). Довод — «По факту 18.3» п.0:
 *  - `philLineage` 22 и `philDirect` 14 — философы главный признак, не
 *    зависящий от языка. Прямой участник входит и в родословную, поэтому
 *    общий ПРЯМОЙ философ весит 36 долей, а общий лишь через предка — 22:
 *    тот, с кем концепция работает сама, определяет её сильнее, чем
 *    философ концепции-деда;
 *  - `terms` 20 и `categories` 14 — самое точное свидетельство («говорят
 *    об одном»), но сравнимо только внутри языка. Терминов в документе
 *    больше и это собственный словарь концепции; имена категорий короче и
 *    общее («Бытие», «Время») — различают хуже;
 *  - `kin` 14 — родство (общий предок-концепция либо одна — предок
 *    другой): сильное свидетельство, но есть только у мета-синтезов;
 *  - `epochs` 6 — грубый признак (эпох десять) и производный от философов:
 *    ловит «не те же, но соседние» (Кант и Гегель);
 *  - `method` 6, `level` 4 — слабые: методов шесть, уровней три, и
 *    случайное совпадение часто (1/6 и 1/3 — потому уровень легче метода).
 */
export const SIMILARITY_WEIGHTS: Readonly<Record<SimilarityFeature, number>> = {
  philDirect: 14,
  philLineage: 22,
  kin: 14,
  terms: 20,
  categories: 14,
  epochs: 6,
  method: 6,
  level: 4,
};

/**
 * Мера словами (решение пользователя: «словами и причинами, а не числом с
 * десятыми»). Число меры клиенту не отдаётся вовсе.
 */
export const SIMILARITY_GRADES = ["strong", "notable", "weak"] as const;
export type SimilarityGrade = (typeof SIMILARITY_GRADES)[number];

/**
 * Нижние границы ступеней по мере 0…1. Ниже `weak` концепция в выдачу не
 * идёт. Привязка (предков нет — знаменатель 86):
 *  - те же философы и тот же метод, общего текста нет либо он не
 *    сравнивался — 48/86 ≈ 0.56, «сильно»; то же и половина терминов
 *    общая — около 0.8;
 *  - один общий философ из двух у каждой и тот же метод — около 0.24–0.29,
 *    «заметно»;
 *  - один общий из трёх у каждой при разном методе — около 0.12, «слабо».
 */
export const SIMILARITY_GRADE_MIN: Readonly<Record<SimilarityGrade, number>> = {
  strong: 0.45,
  notable: 0.22,
  weak: 0.1,
};

/** Ступень по мере; null — ниже порога показа. */
export function similarityGradeOf(score: number): SimilarityGrade | null {
  for (const g of SIMILARITY_GRADES) if (score >= SIMILARITY_GRADE_MIN[g]) return g;
  return null;
}

