/**
 * Похожие концепции (беседа 18.3; врезка «Фаза 18» в 07; 03 §2.22) —
 * признаки, веса и пороги меры, общие серверу и клиенту.
 *
 * Мера сходства двух концепций — взвешенная сумма пересечений признаков
 * (у множеств — коэффициент Жаккара |A∩B| / |A∪B|, у метода и уровня —
 * совпадение), делённая на сумму весов признаков, вошедших в счёт.
 *
 * Что входит в знаменатель:
 *  - признаки ТЕКСТА (термины, категории) — ВСЕГДА, и тогда, когда их
 *    сравнить нельзя (другой язык, витрина) или сравнивать нечего: тогда
 *    они дают ноль. Несравненное не засчитывается. Иначе концепция, чей
 *    текст не сравнивался, судилась бы по одним философам и обходила бы
 *    концепцию того же языка, у которой общие термины ЕСТЬ, но не все
 *    (Жаккар по терминам у близких документов — десятые доли);
 *  - метод и уровень — всегда;
 *  - философы, эпохи — когда множество непусто хотя бы у одной из двух;
 *  - род — когда хотя бы у одной есть предок-концепция. Родословная из
 *    одних философов — обычный случай: отсутствие предков у обеих — не
 *    различие и не сходство, и признак из меры выбывает.
 * Обычный знаменатель, таким образом, 86 (без рода) либо 100.
 *
 * Считается НА ЗАПРОС: попарно в БД ничего не хранится (решение
 * пользователя) — документы правятся, и сохранённая мера врала бы.
 *
 * Признаки БЕЗ языка — философы (прямые и по всей родословной), род (сама
 * концепция и её предки-концепции), метод, уровень, эпохи философов —
 * сравниваются у любых двух концепций, и через границу языков генерации.
 * Признаки ТЕКСТА — термины глоссария и имена категорий — сравниваются
 * только у концепций одного языка генерации и только там, где содержание
 * обеих смотрящему открыто (у витрины не читаются вовсе).
 */

