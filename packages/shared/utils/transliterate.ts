/**
 * Транслитерация для имён файлов экспорта.
 * Дословный порт из philosynth.html [~17453–17477].
 */

const CYR: Readonly<Record<string, string>> = {
  "а": "a", "б": "b", "в": "v", "г": "g", "д": "d", "е": "e", "ё": "yo",
  "ж": "zh", "з": "z", "и": "i", "й": "y", "к": "k", "л": "l", "м": "m",
  "н": "n", "о": "o", "п": "p", "р": "r", "с": "s", "т": "t", "у": "u",
  "ф": "f", "х": "kh", "ц": "ts", "ч": "ch", "ш": "sh", "щ": "sch",
  "ъ": "", "ы": "y", "ь": "", "э": "e", "ю": "yu", "я": "ya",
};

export function transliterate(text: string): string {
  // Шаг 1: кириллица → латиница
  let result = text
    .toLowerCase()
    .split("")
    .map((c) => (CYR[c] !== undefined ? CYR[c] : c))
    .join("");
  // Шаг 2: диакритика → базовые латинские (è→e, ü→u, ñ→n)
  result = result.normalize("NFD").replace(/[\u0300-\u036f]/g, "");
  // Шаг 3: CJK и прочие нелатинские остаются как есть (ФС это поддерживают);
  // убираем только управляющие и проблемные для ФС символы
  return result
    .replace(/[<>:"/\\|?*\x00-\x1f]+/g, "-") // запрещённые в ФС
    .replace(/\s+/g, "-") // пробелы → дефис
    .replace(/-+/g, "-")
    .replace(/^-|-$/g, "")
    .slice(0, 80);
}
