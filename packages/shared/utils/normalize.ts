/**
 * Нормализация имён и типов элементов графа.
 * Дословный порт из philosynth.html [~12905–12924].
 */

/** Убирает [сноски], (пояснения) и декоративные кавычки —
 *  чтобы «Имя» совпадало с Имя */
export function normalizeName(name: string): string {
  return name
    .replace(/\[.*?\]/g, "")
    .replace(/\(.*?\)/g, "")
    .replace(/[«»""]/g, "")
    .trim();
}

/** Убирает суффиксы вида «· П», «- Д», «/ П», «(Д)» из строки типа
 *  категории. Модель иногда добавляет к типу маркер деконструированности/
 *  пересобранности; он ломает легенду (дубли) и бейджи в панели. */
export function normalizeType(t: string | null | undefined): string {
  return (t || "")
    // «онтологическая · П» / «этическая - Д» / «практическая / П»
    .replace(/\s*[·\-–—/]\s*[А-ЯЁA-Zа-яёa-z]{1,3}\s*$/g, "")
    // «онтологическая (П)» — скобочная форма
    .replace(/\s*\(\s*[А-ЯЁA-Zа-яёa-z]{1,3}\s*\)\s*$/g, "")
    .trim();
}
