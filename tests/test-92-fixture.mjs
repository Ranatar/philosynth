/**
 * Фикстура беседы 9.2 — «живая концепция» в миниатюре: разделы в той
 * разметке, какую даёт генерация (обёртка doc-section, подразделы
 * <div data-section><h4>, таблицы doc-table со столбцами шаблонов Registry).
 * Гранулярные таблицы БД наполняются НЕ руками, а парсерами 1.4 — харнесс
 * выгружает концепцию экспортом 4.2 и заводит её импортом 4.3 (урок 5.1:
 * иначе правки идут против несогласованного состояния HTML ↔ БД).
 */
const tbl = (heads, rows) =>
  `<table class="doc-table"><thead><tr>${heads.map((h) => `<th>${h}</th>`).join("")}</tr></thead><tbody>${rows
    .map((r) => `<tr>${r.map((c) => `<td>${c}</td>`).join("")}</tr>`)
    .join("")}</tbody></table>`;
export const sub = (name, body) => `<div data-section="${name}"><h4>${name}</h4>${body}</div>`;
export const sec = (num, title, body) =>
  `<div class="doc-section"><div class="section-num">§ ${num}</div><div class="section-title">${title}</div><div class="doc-content">${body}</div></div>`;

